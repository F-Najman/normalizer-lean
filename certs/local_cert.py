"""Coset-enumeration certificates for the local presentations of B(p^a) (T5).

Relator words: `local_words.txt`, printed by Lean (`scratch/words.lean`: FreeGroup.toWord of each
relator, w/W/s/S = w, w^-1, s, s^-1), so they are exactly the words `CosetCert.check` reads.
Permutations: `local_data_output.txt` (Magma, `local_data.m`).
Writes `local_certs.json` and the Lean file `../NormalizerLean/LocalCerts.lean`.
"""
import json
from coset_cert import parse, build

words = {}
for line in open('local_words.txt'):
    parts = line.split()
    if parts:
        words[parts[0]] = [[(c.lower(), c.islower()) for c in wd] for wd in parts[1:]]

data = parse('local_data_output.txt')
certs = {}
for name, (n, pw, ps) in data.items():
    certs[name] = build(n, pw, ps, words[name])
    print(name, 'n =', n, 'deductions =', len(certs[name]['deds']),
          'max rep length =', max(len(r) for r in certs[name]['reps']))
json.dump(certs, open('local_certs.json', 'w'))

def letter(a):
    return f"(.{a[0]}, {'true' if a[1] else 'false'})"

out = ["import NormalizerLean.CosetCert", "",
       "/-!", "# Coset certificates for the local presentations (T5)", "",
       "Generated by `certs/local_cert.py`; checked in `NormalizerLean/Local.lean` by `decide +kernel`.",
       "-/", "", "namespace NormalizerLean", ""]
for name, c in certs.items():
    out.append(f"def cosetCert_{name} : CosetCert where")
    out.append(f"  n := {c['n']}")
    out.append("  act := fun")
    out.append(f"    | .w => {c['act_w']}")
    out.append(f"    | .s => {c['act_s']}")
    out.append("  actInv := fun")
    out.append(f"    | .w => {c['inv_w']}")
    out.append(f"    | .s => {c['inv_s']}")
    reps = ",\n    ".join("[" + ", ".join(letter(a) for a in r) + "]" for r in c['reps'])
    out.append(f"  reps := [{reps}]")
    out.append(f"  deds := {[tuple(d) for d in c['deds']]}")
    out.append("")
out.append("end NormalizerLean")
open('../NormalizerLean/LocalCerts.lean', 'w').write("\n".join(out) + "\n")

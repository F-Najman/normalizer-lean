"""Generate the Comparator challenges (https://github.com/leanprover/comparator), one for each part.

The 136 statements form six challenges (`ENTRIES`), one for each part. Parts 1, 2, 3, 5 and 6 are the Palomar
entries (`make_formalization.py` writes their metadata); Part 4 is checked in the same way. For each part:

* `Challenge/<Entry>.lean` imports only Mathlib. It copies verbatim the parts of `NormalizerLean/Defs.lean` whose
  definitions the statements use (each part of that file is a self-contained block, beginning at a line
  `-- Part k, moved verbatim …`), then the entry's statements files with each proof
  `:= by apply X' <;> assumption` replaced by `:= sorry` (import lines dropped).
* `Solution/<Entry>.lean` imports the entry's statements files, which prove the same theorems.
* `palomar/<entry>/comparator.json`: the entry's theorem names and the three standard axioms.

Why the copies give the library's constants. Lean shares the auxiliary `_proof_n` lemmas of a file between its
declarations (keyed by their type). Each challenge copies a subsequence of whole parts of `Defs.lean`, in order. In
`Defs.lean` the only auxiliary lemma used outside its own definition is `GammaDelta._proof_4` (Part 2), used by
definitions of Parts 5 and 6, so every challenge that copies Part 5 or 6 also copies Part 2. Two statements in
different statements files, `S7_mem_normG_GammaDeltaR_49` (Part 2) and `card_BG_GammaDeltaR_49` (Part 4), contain a
proof of the same proposition 7 ∣ 49; they are in different challenges, so each challenge gives each its own lemma,
as the library does. Comparator checks the result.

Both Lean files get the module-system header of every source file (`module_header.py`); the copied files are read
without theirs.

Run from the repository root: python3 scripts/make_challenge.py
With --check it only verifies that the files are up to date (exit code 1 if not).
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from module_header import port, unport  # noqa: E402

DEFS = 'NormalizerLean/Defs.lean'
PROOF = re.compile(r":= by apply \w+' <;> assumption")
NAMESPACE = 'NormalizerLean'

# (module suffix, configuration folder, title, parts of the repository, parts of Defs.lean copied, statements files)
ENTRIES = [
    ('Part1', 'part1', 'B(N) = Nor(Γ₀(N))/Γ₀(N)', [1], [1], ['NormalizerLean/Statements.lean']),
    ('Part2', 'part2', 'Γ_Δ(N), Γ(N) and ±Γ₁(N)', [2], [1, 2], ['NormalizerDelta/Statements.lean']),
    ('Part3', 'part3', 'more on Γ_Δ(N), and B₀(N)', [3], [1, 2, 3], ['NormalizerDelta/StatementsExtra.lean']),
    ('Part4', 'part4', 'the order for X(N)', [4], [1, 2, 3, 4], ['NormalizerDelta/StatementsXN.lean']),
    ('Part5', 'part5', 'Cartan modular curves', [5], [1, 2, 5], ['NormalizerDelta/StatementsCartan.lean']),
    ('Part6', 'part6', 'general modular curves X_H', [6], [1, 2, 3, 4, 6], ['NormalizerDelta/StatementsGeneral.lean']),
]

HEADER = """import Mathlib

/-!
# Normalizers of congruence subgroups, {title}: the formal challenge

The {n} statements of {parts_text} of this repository, with every definition they use, over Mathlib alone. This
file is generated by `scripts/make_challenge.py`.

* The definitions are {defs_text} of `NormalizerLean/Defs.lean`, copied verbatim; each part is a self-contained
  block of that file. `Defs.lean` contains no theorems apart from small lemmas used inside the definitions.
* The statements are copied from {stmts_text} with every proof replaced by `sorry`.

`Solution/{module}.lean` imports the statements files, where the same theorems are proved. With the configuration
`palomar/{folder}/comparator.json`, Comparator (https://github.com/leanprover/comparator) checks that each of the
{n} theorems has the same statement here as in the solution, about the same definitions (every definition the
statements use must be the same constant in both), uses no axioms other than `propext`, `Classical.choice` and
`Quot.sound`, and is accepted by the Lean kernel.
-/
"""


def body(path):
    lines = unport(open(path).read()).split('\n')
    assert lines[0].startswith('import '), path
    while lines and (lines[0].startswith('import ') or not lines[0].strip()):
        lines.pop(0)
    return '\n'.join(lines).rstrip('\n') + '\n'


def defs_parts():
    """The six parts of `Defs.lean` (without its imports), split before each line `-- Part k, moved verbatim`."""
    text = body(DEFS)
    pieces = re.split(r'\n(?=-- Part \d, moved verbatim)', text)
    assert len(pieces) == 6 and all(p.startswith(f'-- Part {k}, ') for k, p in enumerate(pieces[1:], 2)), DEFS
    return [p.rstrip('\n') + '\n' for p in pieces]


def listing(items):
    return items[0] if len(items) == 1 else ', '.join(items[:-1]) + ' and ' + items[-1]


def generate():
    parts = defs_parts()
    files, all_names = {}, []
    for module, folder, title, part_numbers, used, statements in ENTRIES:
        chunks, names = [], []
        for path in statements:
            b = body(path)
            found = re.findall(r'^theorem (\S+)', b, re.M)
            b, k = PROOF.subn(':= sorry', b)
            assert k == len(found), (path, k, len(found))
            names += [f'{NAMESPACE}.{x}' for x in found]
            chunks.append(f'\n/-! # From `{path}` (proofs replaced by `sorry`) -/\n\n' + b)
        header = HEADER.format(
            title=title, n=len(names), module=module, folder=folder,
            parts_text=('Part ' if len(part_numbers) == 1 else 'Parts ') + listing([str(k) for k in part_numbers]),
            defs_text=('Part ' if len(used) == 1 else 'Parts ') + listing([str(k) for k in used]),
            stmts_text=listing([f'`{p}`' for p in statements]))
        definitions = ''.join(f'\n/-! # From `{DEFS}`, Part {k} (verbatim) -/\n\n' + parts[k - 1] for k in used)
        files[f'Challenge/{module}.lean'] = port(header + definitions + ''.join(chunks))
        files[f'Solution/{module}.lean'] = port(
            ''.join(f'import {p[:-5].replace("/", ".")}\n' for p in statements) +
            f'\n/-! # The formal solution of `Challenge/{module}.lean`\n\n'
            'The statements files above prove its theorems. -/\n')
        files[f'palomar/{folder}/comparator.json'] = json.dumps({
            'challenge_module': f'Challenge.{module}',
            'solution_module': f'Solution.{module}',
            'theorem_names': names,
            'permitted_axioms': ['propext', 'Quot.sound', 'Classical.choice'],
        }, indent=4, ensure_ascii=False) + '\n'
        all_names += names
    assert len(all_names) == len(set(all_names)) == 136, len(all_names)
    return files


if __name__ == '__main__':
    files = generate()
    if '--check' in sys.argv:
        stale = [f for f, s in files.items() if not os.path.exists(f) or open(f).read() != s]
        print('up to date' if not stale else 'STALE: ' + ', '.join(stale))
        sys.exit(1 if stale else 0)
    for f, s in files.items():
        os.makedirs(os.path.dirname(f), exist_ok=True)
        open(f, 'w').write(s)
    print('wrote', len(files), 'files for', len(ENTRIES), 'challenges')

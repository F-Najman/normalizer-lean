"""Generate Challenge.lean, Solution.lean and Comparator/comparator.json for Comparator
(https://github.com/leanprover/comparator).

* Challenge.lean: imports only Mathlib.  It copies `NormalizerLean/Defs.lean`, which holds the definitions of all
  six parts, then every statements file with each proof `:= by apply X' <;> assumption` replaced by `:= sorry`
  (import lines dropped).  Lean shares auxiliary `_proof_n` lemmas between declarations of the same file, so the copy
  produces the same constants as the library only because the library also has all the definitions in one file.
* Solution.lean: imports the six statements files, which prove the same theorems.
* Comparator/comparator.json: the 136 theorem names and the three standard axioms.
Both Lean files get the module-system header of every source file (`module_header.py`), and the copied files are
read without theirs, so the copy and the library elaborate the definitions in the same setting.

Run from the repository root: python3 scripts/make_challenge.py
With --check it only verifies that the three files are up to date (exit code 1 if not).
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from module_header import port, unport  # noqa: E402

DEFS = 'NormalizerLean/Defs.lean'
STATEMENTS = ['NormalizerLean/Statements.lean', 'NormalizerDelta/Statements.lean',
              'NormalizerDelta/StatementsExtra.lean', 'NormalizerDelta/StatementsXN.lean',
              'NormalizerDelta/StatementsCartan.lean', 'NormalizerDelta/StatementsGeneral.lean']
PROOF = re.compile(r":= by apply \w+' <;> assumption")
NAMESPACE = 'NormalizerLean'

HEADER = """import Mathlib

/-!
# Normalizers of congruence subgroups: the formal challenge

All the {n} statements of this repository in one file, with every definition they use. The definitions are copied
verbatim from `NormalizerLean/Defs.lean`, which holds those of all six parts and contains no theorems apart from
the small lemmas needed by the definitions. The statements are copied from the `Statements*.lean` files with every
proof replaced by `sorry`. This file is generated by `scripts/make_challenge.py`. It imports only Mathlib, so it is
the whole specification.

`Solution.lean` imports the statements files, where the same theorems are proved. With the configuration
`Comparator/comparator.json`, Comparator (https://github.com/leanprover/comparator) checks that each of the
{n} theorems in `Solution` has the same statement as here, about the same definitions (every definition the
statements use must be the same constant in both), uses no axioms other than `propext`, `Classical.choice` and
`Quot.sound`, and is accepted by the Lean kernel.
-/
"""


def body(path):
    lines = unport(open(path).read()).split('\n')
    assert lines[0].startswith('import '), path
    while lines and (lines[0].startswith('import ') or not lines[0].strip()):
        lines.pop(0)
    return '\n'.join(lines).rstrip('\n') + '\n'


def generate():
    parts, names = [], []
    for path in STATEMENTS:
        b = body(path)
        found = re.findall(r'^theorem (\S+)', b, re.M)
        b, k = PROOF.subn(':= sorry', b)
        assert k == len(found), (path, k, len(found))
        names += [f'{NAMESPACE}.{x}' for x in found]
        parts.append(f'\n/-! # From `{path}` (proofs replaced by `sorry`) -/\n\n' + b)
    assert len(names) == len(set(names))
    definitions = f'\n/-! # From `{DEFS}` (verbatim) -/\n\n' + body(DEFS)
    challenge = HEADER.format(n=len(names)) + definitions + ''.join(parts)
    solution = (''.join(f'import {p[:-5].replace("/", ".")}\n' for p in STATEMENTS) +
                '\n/-! # The formal solution\n\nThe statements files above prove the theorems of `Challenge.lean`. -/\n')
    config = json.dumps({
        'challenge_module': 'Challenge',
        'solution_module': 'Solution',
        'theorem_names': names,
        'permitted_axioms': ['propext', 'Quot.sound', 'Classical.choice'],
    }, indent=4, ensure_ascii=False) + '\n'
    return {'Challenge.lean': port(challenge), 'Solution.lean': port(solution), 'Comparator/comparator.json': config}


if __name__ == '__main__':
    files = generate()
    if '--check' in sys.argv:
        stale = [f for f, s in files.items() if open(f).read() != s]
        print('up to date' if not stale else 'STALE: ' + ', '.join(stale))
        sys.exit(1 if stale else 0)
    for f, s in files.items():
        open(f, 'w').write(s)
    print('wrote', ', '.join(files), '-', len(json.loads(files['Comparator/comparator.json'])['theorem_names']),
          'theorems')

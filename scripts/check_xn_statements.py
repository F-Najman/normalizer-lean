"""Numerical checks of the X(N) statements (NormalizerDelta/StatementsXN.lean), by brute force.

1. |SL2(Z/N)| = N^3 prod_{p|N} (1 - 1/p^2)  (N <= 16), and the indices [G0:G1] = phi(N), [G1:G] = N, computed
   in SL2(Z/N) (reduction SL2(Z) -> SL2(Z/N) is onto, and G0(N) > G1(N) > G(N) are preimages).
2. |PSL2(Z/M)| = M^3/2 prod (1 - 1/p^2) for 3 <= M <= 16 (brute force), and the formula for 7 <= M <= 20.
3. Precomputed orders #Aut of the modular automorphism groups of X_Delta(N) for N = M^2 = 49, 64, ..., 196: the
   group Delta generated by -1 and the listed elements is {d = +-1 mod M}, and #Aut equals M^3/2 prod (1 - 1/p^2).
Run: python3 scripts/check_xn_statements.py
"""
from fractions import Fraction
from math import gcd
from sympy import primefactors, totient

def formula(N):
    r = Fraction(N ** 3)
    for p in primefactors(N):
        r *= 1 - Fraction(1, p * p)
    return r

fails = 0
print("1. |SL2(Z/N)|, [G0:G1], [G1:G]")
for N in range(1, 17):
    sl = g0 = g1 = 0
    R = range(N)
    for a in R:
        for b in R:
            for c in R:
                for d in R:
                    if (a * d - b * c - 1) % N == 0:
                        sl += 1
                        if c % N == 0:
                            g0 += 1
                            if (a - 1) % N == 0 and (d - 1) % N == 0:
                                g1 += 1
    ok = (sl == formula(N) and g0 % g1 == 0 and g0 // g1 == totient(N) and g1 == N)
    fails += not ok
    print(f"  N={N:2d} |SL2|={sl:6d} formula={formula(N)} [G0:G1]={g0 // g1} phi={totient(N)} [G1:G]={g1}"
          f" {'ok' if ok else 'FAIL'}")

print("2. |PSL2(Z/M)|")
for M in range(3, 21):
    f = formula(M) / 2
    if M <= 16:
        sl = sum(1 for a in range(M) for b in range(M) for c in range(M) for d in range(M)
                 if (a * d - b * c - 1) % M == 0)
        ok = Fraction(sl, 2) == f
        fails += not ok
        print(f"  M={M:2d} |PSL2|={sl // 2} formula={f} {'ok' if ok else 'FAIL'}")
    else:
        print(f"  M={M:2d} formula={f}")

print("3. table entries with N = M^2")
# (N, generators of Delta besides -1, #Aut in the table, table)
entries = [(49, [27], 168), (64, [25, 63], 192), (81, [8], 324),
           (100, [9], 360), (121, [10], 660), (144, [11, 71], 576),
           (169, [12], 1092), (196, [13], 1008)]
for N, gens, aut in entries:
    M = int(round(N ** 0.5))
    D = {1}
    frontier = [1]
    G = [N - 1] + gens
    while frontier:
        x = frontier.pop()
        for g in G:
            y = x * g % N
            if y not in D:
                D.add(y); frontier.append(y)
    pm = {d for d in range(N) if gcd(d, N) == 1 and (d % M in (1, M - 1))}
    ok = D == pm and Fraction(aut) == formula(M) / 2
    fails += not ok
    print(f"  N={N} M={M} Delta=<-1,{gens}> = {{+-1 mod M}}: {D == pm}, #Aut={aut} formula={formula(M) / 2}"
          f" {'ok' if ok else 'FAIL'}")
print("failures:", fails)

#!/usr/bin/env python3
"""Order of the modular automorphism group Nor(Gamma_Delta(N))/Gamma_Delta(N).

For every N in [NMIN, NMAX] and every subgroup Delta of (Z/N)^x containing -1, compute
  * the genus of X_Delta(N) (coset action of PSL_2(Z) on bottom rows modulo Delta);
  * m = number of left cosets Gamma_0(N) g in the normalizer Nor(Gamma_Delta(N)) of Gamma_Delta(N) in PSL_2(R),
    so that |Nor(Gamma_Delta)/Gamma_Delta| = i_Delta * m;
  * m0 = the same count restricted to g in Nor(Gamma_0(N)), i.e. |Stab_{B(N)}(Gamma_Delta)|;
  * whether every normalizing g lies in M_Delta = D^-1 Gamma_0(n_Delta)^+ D (generalized Newman bound, see below).

Method.  If g normalizes Gamma_Delta then g = A/sqrt(e) with A a primitive integer matrix and e = det A | N
(audit/newman_normalizer.md, Section 2; the argument only uses T, U_N in Gamma_1(N)).  Write A = sigma H with sigma in
SL_2(Z) and H = (a b; 0 d) in Hermite normal form; the coset Gamma_0(N) A determines and is determined by
(Gamma_0(N) sigma, H).  A normalizes Gamma_Delta iff A x A^-1 lies in Gamma_Delta for x in a set of generators of
Gamma_Delta modulo Gamma(N e): T, U_N = (1 0; N 1), V_N = (1+N N; -N 1-N), -1 and lifts of diag(d^-1, d) for generators
d of Delta (Gamma(N)/Gamma(N e) is generated by T^N, U_N, V_N because e | N, and A Gamma(N e) A^-1 lies in Gamma(N)).

M_Delta: eps_Delta = gcd(N, d^2 - 1 : d in Delta), h_Delta = prod_p p^min(v_p(eps_Delta), floor(v_p(N)/2)),
n_Delta = N / h_Delta^2, D = diag(h_Delta, 1).  g is in M_Delta iff D A D^-1 is proportional to a primitive integer
matrix (x y; z w) of determinant e' with e' || n_Delta, n_Delta | z, e' | x and e' | w.

Usage: python3 audit/aut_orders.py [NMIN NMAX [JOBS]]   (default 13 200 8)
Output: TSV on stdout (one line per curve of genus >= 2), checks and a summary on stderr.
"""
import sys
from math import gcd
from multiprocessing import Pool


def factor(n):
    f, p = {}, 2
    while p * p <= n:
        while n % p == 0:
            f[p] = f.get(p, 0) + 1
            n //= p
        p += 1
    if n > 1:
        f[n] = f.get(n, 0) + 1
    return f


def psi(n):
    r = n
    for p in factor(n):
        r = r // p * (p + 1)
    return r


def divisors(n):
    return [d for d in range(1, n + 1) if n % d == 0]


def egcd(a, b):
    if b == 0:
        return (a, 1, 0)
    g, x, y = egcd(b, a % b)
    return (g, y, x - (a // b) * y)


def inv_mod(a, n):
    g, x, _ = egcd(a % n, n)
    assert g == 1
    return x % n


def mul(A, B):
    return ((A[0][0] * B[0][0] + A[0][1] * B[1][0], A[0][0] * B[0][1] + A[0][1] * B[1][1]),
            (A[1][0] * B[0][0] + A[1][1] * B[1][0], A[1][0] * B[0][1] + A[1][1] * B[1][1]))


def adj(A):
    return ((A[1][1], -A[0][1]), (-A[1][0], A[0][0]))


def det(A):
    return A[0][0] * A[1][1] - A[0][1] * A[1][0]


# ---------------------------------------------------------------- subgroups of (Z/N)^x containing -1

def closure_add(S, a, N):
    """Subgroup generated by the subgroup S (frozenset) and a, in the abelian group (Z/N)^x."""
    elems, pw = set(S), a % N
    while pw not in S:
        elems |= {(s * pw) % N for s in S}
        pw = (pw * a) % N
    return frozenset(elems)


def subgroups_with_minus1(N):
    U = [a for a in range(1, N) if gcd(a, N) == 1] if N > 1 else [0]
    start = frozenset({1 % N, (N - 1) % N})
    seen, todo = {start}, [start]
    while todo:
        S = todo.pop()
        for a in U:
            if a not in S:
                T = closure_add(S, a, N)
                if T not in seen:
                    seen.add(T)
                    todo.append(T)
    return sorted(seen, key=lambda S: (-len(S), sorted(S)))


def small_gens(S, N):
    """A short list of generators of S together with -1 (greedy); -1 itself is not listed."""
    cur = frozenset({1 % N, (N - 1) % N})
    gens = []
    for a in sorted(S):
        if a not in cur:
            cur = closure_add(cur, a, N)
            gens.append(a)
        if cur == S:
            break
    assert cur == S
    return gens


# ---------------------------------------------------------------- genus of X_Delta(N)

def genus_data(N, Dset, Dgens):
    rows = [(r, s) for r in range(N) for s in range(N) if gcd(gcd(r, s), N) == 1]
    lab = {}
    nlab = 0
    mults = [N - 1] + Dgens
    for x in rows:
        if x in lab:
            continue
        stack = [x]
        lab[x] = nlab
        while stack:
            r, s = stack.pop()
            for g in mults:
                y = ((g * r) % N, (g * s) % N)
                if y not in lab:
                    lab[y] = nlab
                    stack.append(y)
        nlab += 1
    mu = nlab
    rep = {}
    for x, l in lab.items():
        rep.setdefault(l, x)
    Tm = lambda r, s: (r % N, (r + s) % N)
    Sm = lambda r, s: (s % N, (-r) % N)
    STm = lambda r, s: (s % N, (-r + s) % N)
    nu2 = sum(1 for l, (r, s) in rep.items() if lab[Sm(r, s)] == l)
    nu3 = sum(1 for l, (r, s) in rep.items() if lab[STm(r, s)] == l)
    seen, cusps = set(), 0
    for l, (r, s) in rep.items():
        if l in seen:
            continue
        cusps += 1
        cur = (r, s)
        while lab[cur] not in seen:
            seen.add(lab[cur])
            cur = Tm(*cur)
    g12 = 12 + mu - 3 * nu2 - 4 * nu3 - 6 * cusps
    assert g12 % 12 == 0, (N, sorted(Dset), mu, nu2, nu3, cusps)
    return g12 // 12, mu, nu2, nu3, cusps


# ---------------------------------------------------------------- normalizer

def p1_reps(N):
    """Lifts sigma in SL_2(Z) of representatives of Gamma_0(N) \\ SL_2(Z), i.e. of P^1(Z/N)."""
    U = [u for u in range(1, N) if gcd(u, N) == 1] if N > 1 else [1]
    seen, reps = set(), []
    for c in range(N):
        for d in range(N):
            if gcd(gcd(c, d), N) != 1 or (c, d) in seen:
                continue
            for u in U:
                seen.add(((u * c) % N, (u * d) % N))
            cc, dd = c, d
            if cc == 0:
                cc = N
            k = 0
            while gcd(cc, dd + k * N) != 1:
                k += 1
            dd = dd + k * N
            g, x, y = egcd(dd, cc)          # x*dd + y*cc = 1
            assert g == 1
            reps.append(((x, -y), (cc, dd)))  # det = x*dd + y*cc = 1
    assert len(reps) == psi(N), (N, len(reps))
    return reps


def hnfs(N):
    out = []
    for e in divisors(N):
        for a in divisors(e):
            d = e // a
            for b in range(d):
                if gcd(gcd(a, b), d) == 1:
                    out.append(((a, b), (0, d)))
    return out


def apriori(A, N):
    e = det(A)
    a, b, c, d = A[0][0], A[0][1], A[1][0], A[1][1]
    return (a * a) % e == 0 and (d * d) % e == 0 and (c * c) % (N * e) == 0 and (N * b * b) % e == 0


def gamma_gens(N, gens_mod):
    """Generators of Gamma_Delta modulo Gamma(N^2), for Delta generated by -1 and gens_mod."""
    G = [((1, 1), (0, 1)), ((1, 0), (N, 1)), ((1 + N, N), (-N, 1 - N)), ((-1, 0), (0, -1))]
    for d in gens_mod:
        g, u, v = egcd(d, N)                # u d + v N = 1
        G.append(((u, -v), (N, d)))         # det = u d + v N = 1, lower right d
    return G


def normalizes(A, gens, N, Dset):
    e = det(A)
    Aa = adj(A)
    for x in gens:
        y = mul(mul(A, x), Aa)
        if y[0][0] % e or y[0][1] % e or y[1][0] % e or y[1][1] % e:
            return False
        if (y[1][0] // e) % N or ((y[1][1] // e) % N) not in Dset:
            return False
    return True


def vp(n, p):
    k = 0
    while n % p == 0 and n:
        n //= p
        k += 1
    return k


def in_M(A, N, h, n):
    """Is A/sqrt(det A) in D^-1 Gamma_0(n)^+ D, D = diag(h, 1)?  D A D^-1 = (a, h b; c/h, d)."""
    a, b, c, d = A[0][0], A[0][1], A[1][0], A[1][1]
    # scale by h to clear the denominator of c/h, then make primitive
    x, y, z, w = a * h, b * h * h, c, d * h
    g = gcd(gcd(x, y), gcd(z, w))
    x, y, z, w = x // g, y // g, z // g, w // g
    e = x * w - y * z
    if e < 0:
        x, y, z, w, e = -x, -y, -z, -w, -e
    if e == 0 or n % e or gcd(e, n // e) != 1:
        return False
    return z % n == 0 and x % e == 0 and w % e == 0


def run_level(N):
    out = []
    fN = factor(N)
    h24 = max(h for h in divisors(24) if N % (h * h) == 0)
    reps = p1_reps(N)
    pairs = [mul(s, H) for s in reps for H in hnfs(N)]
    pairs = [A for A in pairs if apriori(A, N)]
    Uall = [u for u in range(1, N) if gcd(u, N) == 1]
    full = frozenset(Uall)
    g0gens = gamma_gens(N, small_gens(full, N))
    in_norm0 = [normalizes(A, g0gens, N, full) for A in pairs]
    phiN = len(Uall)
    for S in subgroups_with_minus1(N):
        gens = small_gens(S, N)
        genus, mu, nu2, nu3, cusps = genus_data(N, S, gens)
        if genus < 2:
            continue
        idx = phiN // len(S)
        gg = gamma_gens(N, gens)
        eps = N
        for d in S:
            eps = gcd(eps, d * d - 1)
        hD = 1
        for p, k in fN.items():
            hD *= p ** min(vp(eps, p), k // 2)
        nD = N // (hD * hD)
        m = m0 = 0
        allM = True
        for A, n0 in zip(pairs, in_norm0):
            if normalizes(A, gg, N, S):
                m += 1
                if n0:
                    m0 += 1
                if not in_M(A, N, hD, nD):
                    allM = False
        out.append((N, len(S), idx, gens, genus, mu, nu2, nu3, cusps, m, idx * m, m0, idx * m0, h24, hD, nD, allM))
    return out


def main():
    nmin = int(sys.argv[1]) if len(sys.argv) > 1 else 13
    nmax = int(sys.argv[2]) if len(sys.argv) > 2 else 200
    jobs = int(sys.argv[3]) if len(sys.argv) > 3 else 8
    with Pool(jobs) as P:
        res = P.map(run_level, range(nmin, nmax + 1), chunksize=1)
    print("N\t|Delta|\ti_Delta\tgens\tgenus\tmu\tnu2\tnu3\tcusps\tm\tAutMod\tm0\tAutInNormG0\th\th_Delta\tn_Delta\tinM")
    rows = [r for lev in res for r in lev]
    for r in rows:
        print("\t".join(str(x) if not isinstance(x, list) else ",".join(map(str, x)) for x in r))
    sys.stderr.write("curves of genus >= 2: %d\n" % len(rows))
    extra = [r for r in rows if r[10] != r[12]]
    sys.stderr.write("curves with normalizer not inside Nor(Gamma_0(N)): %d\n" % len(extra))
    sys.stderr.write("normalizer inside M_Delta for all curves: %s\n" % all(r[16] for r in rows))
    sys.stderr.write("extra elements only when h_Delta != h(N): %s\n" % all(r[14] != r[13] for r in extra))


if __name__ == "__main__":
    main()
